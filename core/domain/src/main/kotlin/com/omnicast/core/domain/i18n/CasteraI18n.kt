    fun t(key: String, lang: String): String {
        val effectiveLang = if (lang == "system" || lang.isBlank()) {
            java.util.Locale.getDefault().language.lowercase()
        } else {
            lang.lowercase()
        }
        val dict = translations[effectiveLang] ?: translations["en"] ?: translations["es"] ?: emptyMap()
        return dict[key] ?: translations["es"]?.get(key) ?: key
    }
